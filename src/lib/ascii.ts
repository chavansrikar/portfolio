const UNKNOWN = ['█████', '█████', '█████', '█████', '█████']

/** Render a string into ASCII block-art lines. */
export function toAscii(text: string): string[] {
  const chars = text.toUpperCase().split('')
  const rows: string[] = ['', '', '', '', '']
  for (const ch of chars) {
    const glyph = FONT[ch] ?? UNKNOWN
    for (let r = 0; r < 5; r++) rows[r] += glyph[r] + ' '
  }
  return rows
}

export function toAsciiString(text: string): string {
  return toAscii(text).join('\n')
}

