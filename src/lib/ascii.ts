/**
 * Characters used by the "matrix rain" background.
 * Pure ASCII only — katakana and box-drawing glyphs are missing from many
 * monospace fonts and would render as tofu boxes.
 */
export const RAIN_CHARS =
  '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz<>\\|=+-*#$%&@:/\\<>[]{}'

/** Build a scrolling ASCII rain column. */
export function makeRainColumn(width: number, height: number, seed = 0): string[] {
  let s = seed * 9301 + 49297
  const rnd = () => {
    s = (s * 9301 + 49297) % 233280
    return s / 233280
  }
  const grid: string[][] = []
  for (let y = 0; y < height; y++) {
    grid[y] = []
    for (let x = 0; x < width; x++) {
      grid[y][x] = RAIN_CHARS[Math.floor(rnd() * RAIN_CHARS.length)]
    }
  }
  return grid.map((row) => row.join(''))
}

